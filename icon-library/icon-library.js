// 初始化函数
function init() {
    const container = document.getElementById('icon-container');
    const loading = document.getElementById('loading');
    const totalCount = document.getElementById('total-count');
    const navList = document.getElementById('nav-list');
    
    // 计算总图标数量
    let total = 0;
    for (const category in iconData) {
        total += iconData[category].length;
    }
    
    totalCount.textContent = `共包含 ${total} 个图标`;
    
    // 生成导航列表
    for (const category in iconData) {
        const navItem = document.createElement('li');
        navItem.className = 'nav-item';
        
        const navLink = document.createElement('a');
        navLink.className = 'nav-link';
        navLink.href = `#${category}`;
        navLink.textContent = category;
        
        navItem.appendChild(navLink);
        navList.appendChild(navItem);
    }
    
    // 动态生成图标
    for (const category in iconData) {
        const categoryDiv = document.createElement('div');
        categoryDiv.className = 'category';
        categoryDiv.id = category;
        
        const categoryTitle = document.createElement('h2');
        categoryTitle.textContent = category;
        categoryDiv.appendChild(categoryTitle);
        
        const iconsGrid = document.createElement('div');
        iconsGrid.className = 'icons-grid';
        
        // 去重处理
        const uniqueIcons = [...new Set(iconData[category])];
        
        uniqueIcons.forEach(icon => {
            const iconItem = createIconItem(icon);
            iconsGrid.appendChild(iconItem);
        });
        
        categoryDiv.appendChild(iconsGrid);
        container.appendChild(categoryDiv);
    }
    
    // 隐藏加载提示
    loading.style.display = 'none';
    
    // 初始化复制功能
    initCopyFunctionality();
    
    // 初始化导航滚动功能
    initNavScrollFunctionality();
}

// 初始化导航滚动功能
function initNavScrollFunctionality() {
    // 平滑滚动
    document.querySelectorAll('.nav-link').forEach(link => {
        link.addEventListener('click', (e) => {
            e.preventDefault();
            const targetId = link.getAttribute('href');
            const targetElement = document.querySelector(targetId);
            
            if (targetElement) {
                targetElement.scrollIntoView({ 
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    });
}

// 创建图标元素
function createIconItem(icon) {
    const item = document.createElement('div');
    item.className = 'icon-item';
    item.dataset.code = icon;
    item.dataset.category = Array.from(icon).map(char => char.codePointAt(0).toString(16)).join('-');
    
    const iconSpan = document.createElement('span');
    iconSpan.className = 'icon';
    iconSpan.textContent = icon;
    
    const codeSpan = document.createElement('span');
    codeSpan.className = 'icon-code';
    codeSpan.textContent = icon;
    
    const copyBtn = document.createElement('button');
    copyBtn.className = 'copy-btn';
    copyBtn.textContent = '复制';
    
    item.appendChild(iconSpan);
    item.appendChild(codeSpan);
    item.appendChild(copyBtn);
    
    return item;
}

// 初始化复制功能
function initCopyFunctionality() {
    // 复制按钮点击事件
    document.querySelectorAll('.copy-btn').forEach(button => {
        button.addEventListener('click', () => {
            const iconItem = button.parentElement;
            const iconCode = iconItem.dataset.code;
            copyIcon(iconCode, button);
        });
    });
    
    // 图标点击事件
    document.querySelectorAll('.icon-item').forEach(item => {
        item.addEventListener('click', (e) => {
            if (!e.target.classList.contains('copy-btn')) {
                const iconCode = item.dataset.code;
                const button = item.querySelector('.copy-btn');
                copyIcon(iconCode, button);
            }
        });
    });
}

// 复制图标到剪贴板
function copyIcon(iconCode, button) {
    navigator.clipboard.writeText(iconCode).then(() => {
        button.textContent = '已复制';
        button.classList.add('copied');
        
        setTimeout(() => {
            button.textContent = '复制';
            button.classList.remove('copied');
        }, 2000);
    }).catch(err => {
        console.error('复制失败:', err);
        alert('复制失败，请手动复制');
    });
}

// 页面加载完成后初始化
document.addEventListener('DOMContentLoaded', init);